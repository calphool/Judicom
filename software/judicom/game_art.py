def barrier_mask():
    """One shelter, 22 x 15: a block with sloping top corners and an arch cut out underneath.  Rows of 0 / 1."""
    w, h = 22, 15
    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            lit = True
            if y < 4 and (x < 4 - y or x >= w - 4 + y):              # the sloping top corners
                lit = False
            ax = abs(x - (w - 1) / 2)                                # the arch: 10 wide, 6 high, round at the top
            if y >= h - 6 and ax < 5 and not (y == h - 6 and ax > 3):
                lit = False
            row.append(1 if lit else 0)
        rows.append(row)
    return rows


